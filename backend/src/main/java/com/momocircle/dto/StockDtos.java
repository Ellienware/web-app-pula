package com.momocircle.dto;

import com.momocircle.domain.enums.StockFulfilmentOption;
import com.momocircle.domain.enums.StockOrderStatus;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;

/**
 * DTOs for PULA Market — Stock / B2B procurement (brief §12-15).
 *
 * Design notes:
 * - Backend is authoritative for all prices, totals, and MOQ validation.
 * - Clients never supply a price total; they supply quantities only, and the
 *   server computes pricePerPack × quantityPacks and enforces MOQ.
 * - StockOrder IDs are opaque to the client; the client never submits an ID
 *   to claim ownership — ownership is established from the JWT-authenticated
 *   user's business.
 */
public class StockDtos {

    // ---- Wholesale Products ----

    public record CreateWholesaleProductRequest(
            @NotBlank String name,
            String description,
            /** Optional SKU. If provided, must be unique within this supplier's catalogue. */
            String sku,
            String category,
            @Min(1) int packSize,
            @Min(1) int moq,
            @NotNull @Min(0) BigDecimal pricePerPack,
            @Min(0) int availableStock
    ) {}

    public record UpdateWholesaleProductRequest(
            String name,
            String description,
            String sku,
            String category,
            Integer packSize,
            Integer moq,
            BigDecimal pricePerPack,
            Integer availableStock,
            Boolean active
    ) {}

    public record WholesaleProductResponse(
            String id,
            String supplierBusinessId,
            String supplierBusinessName,
            String name,
            String description,
            String sku,
            String category,
            int packSize,
            int moq,
            BigDecimal pricePerPack,
            String currency,
            int availableStock,
            boolean active,
            Instant createdAt
    ) {}

    // ---- Stock Cart ----

    public record AddStockCartItemRequest(
            @NotBlank String wholesaleProductId,
            @Min(1) int quantityPacks
    ) {}

    public record StockCartItemResponse(
            String id,
            String wholesaleProductId,
            String productName,
            String sku,
            int packSize,
            int moq,
            BigDecimal pricePerPack,
            String currency,
            int quantityPacks,
            BigDecimal lineTotal,
            boolean moqMet,
            boolean stockSufficient,
            String supplierBusinessId,
            String supplierBusinessName
    ) {}

    public record StockCartResponse(
            List<StockCartItemResponse> items,
            BigDecimal subtotal,
            String currency,
            boolean valid,
            List<String> validationMessages
    ) {}

    // ---- Stock Orders ----

    /**
     * A buyer submits one of these per supplier group in their cart.
     * Checkout validates MOQ, stock, and computes all totals server-side —
     * the client supplies only quantities and fulfilment choice.
     */
    public record PlaceStockOrderRequest(
            /** Idempotency key (UUID generated by the client). Prevents duplicate orders on retry. */
            @NotBlank String idempotencyKey,
            @NotNull StockFulfilmentOption fulfilmentMethod,
            /** Required for WHOLESALER_DELIVERY and PULA_RIDE_DELIVERY. */
            String deliveryAddress,
            /** Save-to-Buy: optional APPROVED request for this buyer. The order only references it. */
            String saveToBuyRequestId
    ) {
        public PlaceStockOrderRequest(String idempotencyKey, StockFulfilmentOption fulfilmentMethod, String deliveryAddress) {
            this(idempotencyKey, fulfilmentMethod, deliveryAddress, null);
        }
    }

    public record StockOrderItemResponse(
            String wholesaleProductId,
            String productName,
            String sku,
            int packSizeSnapshot,
            int quantityPacks,
            BigDecimal pricePerPackSnapshot,
            BigDecimal lineTotal
    ) {}

    public record StockOrderResponse(
            String id,
            String buyerBusinessId,
            String buyerBusinessName,
            String supplierBusinessId,
            String supplierBusinessName,
            List<StockOrderItemResponse> items,
            BigDecimal subtotal,
            BigDecimal deliveryFee,
            BigDecimal total,
            String currency,
            StockOrderStatus status,
            StockFulfilmentOption fulfilmentMethod,
            String deliveryAddress,
            Instant createdAt,
            Instant updatedAt
    ) {}
}
